"""Collects the per-version sim results archived in experiments/history/ (body-v2 ... body-v3.34) into history/sim_history.csv and
history/sim_history.md: total mass, standing margin, head+arm (e) margin, head-pitch peak torque, main / efficient gait success + speed.
usage: python tools/history_table.py"""
import os, re, json, glob, csv
H = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "history")
def vkey(d):
    m = re.match(r"body-v(\d+)(?:\.(\d+))?(.*)", d); return (int(m.group(1)), int(m.group(2) or 0), m.group(3)) if m else (99, 0, d)
rows = []
for d in sorted({p.split(os.sep)[-3] for p in glob.glob(os.path.join(H, "body-*", "sim", "results_v*.json"))}, key=vkey):
    S = os.path.join(H, d, "sim"); r = {}
    for f in sorted(glob.glob(os.path.join(S, "results_v*.json"))):
        if re.search(r"results_v\d?(_[\w.]+)?\.json$", f): r = json.load(open(f)); break
    def W(n):
        p = os.path.join(S, n); return json.load(open(p)) if os.path.exists(p) else {}
    w, we = W("walk_v3.json") or W("walk_v2.json"), W("walk_v3_eff.json") or W("walk_v2_eff.json")
    st = (r.get("a_standing") or {}); st = st.get("crouch_0.10", st) if isinstance(st, dict) else {}
    e = r.get("e_head_arm_motion") or {}; tq = (e.get("torque") or {}).get("head_pitch", {})
    rows.append(dict(version=d, total_mass_kg=r.get("total_mass_kg"), stand_margin_mm=st.get("margin_min_mm"), e_margin_mm=e.get("min_support_margin_mm"),
                     head_pitch_peak_Nm=tq.get("peak") if isinstance(tq, dict) else None,
                     main_succ=w.get("success_rate_randomized"), main_speed=w.get("speed_mps_randomized_mean"),
                     eff_succ=we.get("success_rate_randomized"), eff_speed=we.get("speed_mps_randomized_mean")))
with open(os.path.join(H, "sim_history.csv"), "w", newline="") as f:
    c = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n"); c.writeheader(); c.writerows(rows)
with open(os.path.join(H, "sim_history.md"), "w") as f:
    f.write("# Sim history per body version (from the archived results_v3.json / walk_v3*.json; generated by tools/history_table.py)\n\n")
    f.write("Each row is the LAST results_v3.json / walk_v3*.json written in that version's sim folder, so a row can be a side study rather than the release run (body-v3.32: the last write was a study run, its release run is v332_r2 in the v3.32 sim_summary.txt: 20/20 main, 20/20 eff). The release-run lines for v3.32-v3.34 are in history/body-v3.3x-body/sim/sim_summary.txt.\n\n")
    f.write("| " + " | ".join(rows[0]) + " |\n|" + "---|" * len(rows[0]) + "\n")
    for r in rows: f.write("| " + " | ".join("" if v is None else str(v) for v in r.values()) + " |\n")
print(len(rows), "versions"); print(open(os.path.join(H, "sim_history.md")).read())
